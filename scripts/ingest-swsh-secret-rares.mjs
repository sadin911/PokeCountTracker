// Map and generate full card objects with IDs and image fallbacks
const existingKeys = new Set(currentCards.map(c => `${c.set?.id || ''}_${c.collectorNumber || c.localId}`));

let addedCount = 0;
let nextIdNum = 10000;

for (const card of secretCards) {
  const key = `${card.set.id}_${card.collectorNumber}`;
  if (!existingKeys.has(key)) {
    const newId = `TH-SEC-${nextIdNum++}`;
    const encodedName = encodeURIComponent(card.name);
    const formattedCol = card.collectorNumber.replace('/', '-');
    const localPath = `/PokeCountTracker/card-images/${card.set.id}/${formattedCol}_${encodedName}.webp`;

    currentCards.push({
      id: newId,
      localId: newId,
      name: card.name,
      stage: card.stage,
      category: card.category,
      hp: card.hp,
      types: card.types,
      set: card.set,
      imageUrl: localPath,
      imageUrlHigh: localPath,
      collectorNumber: card.collectorNumber,
      regulationMark: card.regulationMark,
      officialImageUrl: `https://asia.pokemon-card.com/th/card-img/${card.set.id}_${card.collectorNumber}.png`,
      rarityCode: card.rarityCode,
    });
    existingKeys.add(key);
    addedCount++;
  }
}

console.log(`Added ${addedCount} Secret Rare cards (HR, UR Gold, SR) to dataset.`);

fs.writeFileSync(jsonPath, JSON.stringify(currentCards, null, 2), 'utf8');
console.log(`Updated ${jsonPath} with total ${currentCards.length} cards.`);
